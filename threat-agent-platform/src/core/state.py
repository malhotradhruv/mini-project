# 4. RED-TEAM ADVERSARY SIMULATION OUTPUT
# =============================================================================
class AdversaryHypothesis(BaseModel):
    """Predictive red-team adversarial trajectory simulation."""
    predicted_next_step: str = Field(..., description="What the attacker will do next based on uncovered exposure")
    target_asset: str = Field(..., description="The next logical machine or subnet targeted")
    mitre_tactic: str = Field(..., description="Predicted MITRE tactic")
    exploit_vector: str = Field(..., description="Specific vulnerability or method")


# =============================================================================
# 5. INCIDENT & CONTAINMENT REPORT
# =============================================================================
class SwarmIncidentReport(BaseModel):
    """Consolidated incident report synthesized across the autonomous agent swarm."""
    incident_active: bool = Field(default=False)
    threat_severity: Literal["BENIGN", "LOW", "MEDIUM", "HIGH", "CRITICAL"] = Field(default="BENIGN")
    consensus_confidence: float = Field(default=0.0, ge=0.0, le=1.0)
    root_cause_analysis: str = Field(default="No attack pattern identified.")
    correlated_entities: Dict[str, List[str]] = Field(default_factory=dict)
    adversary_trajectory: Optional[AdversaryHypothesis] = None
    containment_commands: List[str] = Field(
        default_factory=list,
        description="Executable shell/firewall commands (iptables, systemctl, etc.)",
    )


# =============================================================================
# 6. GLOBAL CYCLIC SWARM STATE
# =============================================================================
class SwarmState(TypedDict):
    """Global immutable state container traversed across autonomous cyclic LangGraph nodes."""
    task_id: str
    # Ingestion streams
    raw_email_stream: Optional[str]
    raw_log_stream: Optional[str]
    target_cidr: Optional[str]

    # Active War-Room Dialogue (Appended via operator.add)
    messages: Annotated[List[AgentMessage], operator.add]

    # Accumulated Specialist Findings (Appended via operator.add)
    specialist_findings: Annotated[List[AgentFinding], operator.add]

    # Swarm Routing Control
    next_speaker: str
    iteration_count: int
    max_iterations: int
    consensus_reached: bool

    # Final Output
    final_incident_report: Optional[SwarmIncidentReport]


def create_initial_swarm_state(
    task_id: str = "",
    raw_email_stream: Optional[str] = None,
    raw_log_stream: Optional[str] = None,
    target_cidr: Optional[str] = None,
    max_iterations: int = 5,
) -> SwarmState:
    """Helper factory to instantiate an initial clean SwarmState dictionary."""
    return {
        "task_id": task_id,
        "raw_email_stream": raw_email_stream,
        "raw_log_stream": raw_log_stream,
        "target_cidr": target_cidr,
        "messages": [],
        "specialist_findings": [],
        "next_speaker": "LeadSupervisor",
        "iteration_count": 0,
        "max_iterations": max_iterations,
        "consensus_reached": False,
        "final_incident_report": None,
    }


