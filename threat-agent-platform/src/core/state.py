# 7. BACKWARD COMPATIBILITY SCHEMAS & FACTORIES
# =============================================================================
class ExtractedArtifacts(BaseModel):
    """Technical Indicators of Compromise (IOCs) and network entities."""
    ips: List[str] = Field(default_factory=list, description="Public/Private IPv4 addresses detected")
    domains: List[str] = Field(default_factory=list, description="Extracted FQDNs or base domains")
    urls: List[str] = Field(default_factory=list, description="Full HTTP/HTTPS URIs extracted")
    ports: List[int] = Field(default_factory=list, description="Open network ports discovered")
    cves: List[str] = Field(default_factory=list, description="NIST NVD CVE identifiers mapped")
    timestamps: List[str] = Field(default_factory=list, description="Log event timestamps HH:MM:SS")


class AttackStage(BaseModel):
    """Reconstructed stage of a multi-vector attack mapped to MITRE ATT&CK."""
    stage_number: int
    tactic: str = Field(..., description="MITRE ATT&CK tactic (e.g., Initial Access, Execution)")
    description: str
    correlated_indicator: str


class CorrelatedIncidentReport(BaseModel):
    """Consolidated incident report synthesized across multiple agent telemetry vectors."""
    incident_detected: bool = Field(default=False)
    threat_severity: str = Field(default="LOW", description="LOW | MEDIUM | HIGH | CRITICAL")
    confidence_score: float = Field(default=0.0, ge=0.0, le=1.0)
    participating_agents: List[str] = Field(default_factory=list)
    common_artifacts: ExtractedArtifacts = Field(default_factory=ExtractedArtifacts)
    attack_timeline: List[AttackStage] = Field(default_factory=list)
    forensic_narrative: str = Field(default="No coordinated activity identified.")
    containment_playbook: List[str] = Field(default_factory=list)


class ThreatState(TypedDict):
    """Legacy state container traversed across LangGraph nodes."""
    task_id: str
    raw_email: str
    raw_logs: str
    target_network: str
    findings: Annotated[List[AgentFinding], operator.add]
    correlation_result: Optional[CorrelatedIncidentReport]
    audit_trace: Annotated[List[str], operator.add]


def create_initial_threat_state(
    task_id: str = "",
    raw_email: str = "",
    raw_logs: str = "",
    target_network: str = "",
) -> ThreatState:
    """Helper factory to instantiate an initial clean ThreatState dictionary."""
    return {
        "task_id": task_id,
        "raw_email": raw_email,
        "raw_logs": raw_logs,
        "target_network": target_network,
        "findings": [],
        "correlation_result": None,
        "audit_trace": [],
    }


