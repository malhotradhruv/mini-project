"""Central LangGraph Swarm State and Typed Contract Models for Autonomous Multi-Agent SOC.

Based on the IEEE Access research paper:
"A Multi-Agent System for Cybersecurity Threat Detection and Correlation Using Large Language Models"
(Hmimou et al., 2025).

Defines immutable Pydantic v2 data models and the TypedDict graph state supporting:
1. Multi-turn conversational agency and inter-agent debate history
2. Autonomous sub-task delegation and war-room messaging
3. Grounded MITRE ATT&CK adversarial simulation and hypothesis generation
4. Cyclic state machines with asynchronous operator.add reducers
"""

from typing import TypedDict, Annotated, List, Dict, Any, Optional, Literal
import operator
from pydantic import BaseModel, Field, model_validator


# =============================================================================
# 1. SWARM MESSAGE EXCHANGE PROTOCOL
# =============================================================================
class AgentMessage(BaseModel):
    """Inter-agent conversational message and delegation exchange."""
    sender: str = Field(
        ...,
        description="Agent name (e.g. LeadSupervisor, EmailHunter, LogForensics, NetworkRecon, RedTeamSim)",
    )
    recipient: str = Field(
        default="ALL",
        description="Target agent or 'ALL' for broadcast",
    )
    content: str = Field(
        ...,
        description="Human/Agent readable conversational message, challenge, or finding",
    )
    action_type: Literal["DELEGATE", "OBSERVE", "CHALLENGE", "VERIFY", "CONSENSUS"] = Field(
        default="OBSERVE",
        description="Pragmatic role of this message in the war room",
    )
    artifacts: Dict[str, Any] = Field(
        default_factory=dict,
        description="Structured artifacts (IPs, hashes, CVEs)",
    )
    timestamp: str = Field(
        ...,
        description="ISO 8601 or event timestamp",
    )


# =============================================================================
# 2. MITRE ATT&CK MAPPING
# =============================================================================
class MitreTechnique(BaseModel):
    """Formal MITRE ATT&CK technique taxonomy mapping."""
    technique_id: str = Field(..., description="e.g., T1566.002, T1110.001, T1190")
    tactic: str = Field(..., description="e.g., Initial Access, Persistence, Privilege Escalation")
    description: str


# =============================================================================
# 3. INDIVIDUAL AGENT FORENSIC FINDING
# =============================================================================
class AgentFinding(BaseModel):
    """Forensic report generated by an individual specialist worker agent."""
    agent_id: str = Field(..., description="Worker agent identifier (e.g. EmailHunter, LogForensics)")
    is_malicious: bool = Field(..., description="Binary threat classification")
    confidence_score: float = Field(..., ge=0.0, le=1.0, description="Confidence rating between 0 and 1")
    mitre_tags: List[MitreTechnique] = Field(default_factory=list, description="Associated MITRE techniques")
    technical_indicators: List[str] = Field(default_factory=list, description="Deterministic flags and forensic heuristics")
    extracted_entities: Dict[str, List[Any]] = Field(
        default_factory=lambda: {"ips": [], "domains": [], "ports": [], "cves": []},
        description="Extracted IOC entities mapped by category",
    )
    raw_evidence: Dict[str, Any] = Field(default_factory=dict, description="Raw tool outputs for auditing")
    summary: str = Field(..., description="Chain-of-thought semantic forensic summary")

    @model_validator(mode="before")
    @classmethod
    def _bridge_legacy_fields(cls, values: Any) -> Any:
        """Seamless bridge for legacy field names to ensure backward compatibility."""
        if isinstance(values, dict):
            # Map risk_score -> confidence_score
            if "risk_score" in values and "confidence_score" not in values:
                values["confidence_score"] = float(values.pop("risk_score"))

            # Map analyst_summary -> summary
            if "analyst_summary" in values and "summary" not in values:
                values["summary"] = str(values.pop("analyst_summary"))

            # Map indicators -> technical_indicators
            if "indicators" in values and "technical_indicators" not in values:
                values["technical_indicators"] = list(values.pop("indicators"))

            # Map legacy artifacts -> extracted_entities
            if "artifacts" in values and values["artifacts"] is not None:
                art = values.pop("artifacts")
                art_dict = art.model_dump() if hasattr(art, "model_dump") else (art if isinstance(art, dict) else {})
                existing_entities = values.get("extracted_entities") or {"ips": [], "domains": [], "ports": [], "cves": []}
                if not isinstance(existing_entities, dict):
                    existing_entities = {"ips": [], "domains": [], "ports": [], "cves": []}

                for k in ["ips", "domains", "ports", "cves"]:
                    if k in art_dict and art_dict[k]:
                        existing_entities[k] = [str(x) for x in art_dict[k]]
                values["extracted_entities"] = existing_entities

        return values

    # Legacy Backward-Compatibility Property Bridges
    @property
    def risk_score(self) -> float:
        """Legacy compatibility alias for confidence_score."""
        return self.confidence_score

    @property
    def analyst_summary(self) -> str:
        """Legacy compatibility alias for summary."""
        return self.summary

    @property
    def indicators(self) -> List[str]:
        """Legacy compatibility alias for technical_indicators."""
        return self.technical_indicators

    @property
    def artifacts(self) -> "ExtractedArtifacts":
        """Legacy compatibility bridge returning ExtractedArtifacts."""
        ips = self.extracted_entities.get("ips", [])
        domains = self.extracted_entities.get("domains", [])
        ports = [int(p) for p in self.extracted_entities.get("ports", []) if str(p).isdigit()]
        cves = self.extracted_entities.get("cves", [])
        return ExtractedArtifacts(ips=ips, domains=domains, ports=ports, cves=cves)


