"""Data contract schemas for Threat Agent Platform.

Strict Pydantic v2 models enforcing rigid validation across all agent inputs,
deterministic tool outputs, LLM semantic syntheses, and correlation reports.
Reference: IEEE Access (Hmimou et al., 2025).
"""

from typing import Any, Dict, List, Literal
from pydantic import BaseModel, ConfigDict, Field, field_validator


class TaskInput(BaseModel):
    """Input payload dispatched to a specialized detection agent."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    task_type: Literal["email", "log", "ip"] = Field(
        ...,
        description="Target agent domain: 'email', 'log', or 'ip'",
    )
    payload: str = Field(
        ...,
        min_length=1,
        description="Raw payload content to analyze (email text, log line, or IP address)",
    )


class ExtractedEntities(BaseModel):
    """Structured Indicators of Compromise (IOCs) and network entities."""

    model_config = ConfigDict(extra="ignore", str_strip_whitespace=True)

    ips: List[str] = Field(
        default_factory=list,
        description="Extracted IPv4 and IPv6 network addresses",
    )
    domains: List[str] = Field(
        default_factory=list,
        description="Extracted domain names, hostnames, and URLs",
    )
    timestamps: List[str] = Field(
        default_factory=list,
        description="Normalized chronological timestamps parsed from payloads",
    )
    ports: List[int] = Field(
        default_factory=list,
        description="Network port numbers identified in logs or audits",
    )

    @field_validator("ports")
    @classmethod
    def validate_port_ranges(cls, ports: List[int]) -> List[int]:
        """Ensure all ports are valid 16-bit integers."""
        for port in ports:
            if not (0 <= port <= 65535):
                raise ValueError(f"Port {port} is out of valid range (0-65535)")
        return sorted(list(set(ports)))

    @field_validator("ips", "domains", "timestamps")
    @classmethod
    def deduplicate_lists(cls, values: List[str]) -> List[str]:
        """Deduplicate extracted strings while preserving ordering."""
        seen = set()
        deduped = []
        for v in values:
            item = v.strip()
            if item and item not in seen:
                seen.add(item)
                deduped.append(item)
        return deduped


class AgentReport(BaseModel):
    """Strict structured report generated by a domain-specific agent."""

    model_config = ConfigDict(extra="ignore", str_strip_whitespace=True)

    agent_id: str = Field(
        ...,
        description="Identifier of reporting agent (e.g., 'email_agent', 'log_agent', 'ip_agent')",
    )
    is_malicious: bool = Field(
        ...,
        description="Binary verdict indicating whether malicious activity was detected",
    )
    risk_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Normalized risk metric strictly bounded between 0.0 and 1.0",
    )
    entities: ExtractedEntities = Field(
        default_factory=ExtractedEntities,
        description="Deterministic IOCs extracted from the payload",
    )
    technical_indicators: List[str] = Field(
        default_factory=list,
        description="Deterministic rule matches, threat signatures, and heuristics",
    )
    raw_evidence: Dict[str, Any] = Field(
        default_factory=dict,
        description="Verifiable computational evidence from deterministic tools",
    )
    explanation: str = Field(
        ...,
        min_length=1,
        description="Semantic synthesis and threat justification generated by LLM or fallback",
    )

    @field_validator("risk_score")
    @classmethod
    def round_risk_score(cls, v: float) -> float:
        """Round risk score to 4 decimal places for precision consistency."""
        return round(float(v), 4)


class CorrelatedIncident(BaseModel):
    """Cross-agent synthesized incident report from the Correlator."""

    model_config = ConfigDict(extra="ignore", str_strip_whitespace=True)

    incident_detected: bool = Field(
        ...,
        description="Whether a multi-vector correlated security incident was confirmed",
    )
    confidence_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Overall incident confidence score bounded between 0.0 and 1.0",
    )
    participating_agents: List[str] = Field(
        default_factory=list,
        description="Identifiers of agents whose findings contributed to the correlation",
    )
    correlated_entities: ExtractedEntities = Field(
        default_factory=ExtractedEntities,
        description="Aggregated, deduplicated IOCs linked across disparate vectors",
    )
    attack_timeline: List[str] = Field(
        default_factory=list,
        description="Reconstructed chronological attack sequence across vectors",
    )
    narrative: str = Field(
        ...,
        min_length=1,
        description="Holistic contextual threat narrative synthesizing the complete campaign",
    )
    remediation_steps: List[str] = Field(
        default_factory=list,
        description="Prioritized, actionable remediation guidance for SOC analysts",
    )

    @field_validator("confidence_score")
    @classmethod
    def round_confidence_score(cls, v: float) -> float:
        """Round confidence score to 4 decimal places."""
        return round(float(v), 4)
